const test = require('tape')
const DPTLib = require('../../src/dptlib')
const commontest = require('./commontest')

/**
 * RGBW raw values 4x(0..255)
 * 6 bytes: 1 byte for each color (R,G,B,W), 1 unused byte, 1 byte for channel selection (bitmask)
 */

commontest.do('DPT251', [
  { apdu_data: [0x00, 0xff, 0x00, 0x00, 0x00, 0x04], jsval: {mask: 0x04, green: 0xff}},
  { apdu_data: [0x7f, 0xff, 0x00, 0x00, 0x00, 0x0c], jsval: {mask: 0x0c, red: 0x7f, green: 0xff}},
  { apdu_data: [0x7f, 0xff, 0xcc, 0x33, 0x00, 0x0f], jsval: {mask: 0x0f, red: 0x7f, green: 0xff, blue: 0xcc, white: 0x33}},
  { apdu_data: [0x00, 0x00, 0x80, 0x00, 0x00, 0x02], jsval: {mask: 0x02, blue: 0x80}},
  { apdu_data: [0x00, 0x00, 0x00, 0x21, 0x00, 0x01], jsval: {mask: 0x01, white: 0x21}}
]);

commontest.do('DPT251.600', [
  { apdu_data: [0x00, 0xff, 0x00, 0x00, 0x00, 0x04], jsval: {mask: 0x04, green: 0xff}},
  { apdu_data: [0x7f, 0xff, 0x00, 0x00, 0x00, 0x0c], jsval: {mask: 0x0c, red: 0x7f, green: 0xff}},
  { apdu_data: [0x7f, 0xff, 0xcc, 0x33, 0x00, 0x0f], jsval: {mask: 0x0f, red: 0x7f, green: 0xff, blue: 0xcc, white: 0x33}},
  { apdu_data: [0xff, 0x00, 0x00, 0x00, 0x00, 0x08], jsval: {mask: 0x08, red: 0xff}},
  { apdu_data: [0x00, 0x00, 0x00, 0x21, 0x00, 0x01], jsval: {mask: 0x01, white: 0x21}}
]);

test('DPT251.600: mask handling', function(t) {
  const automaticMask = {};
  DPTLib.populateAPDU({red: 0x7f, blue: 0xcc}, automaticMask, 'DPT251.600');
  t.deepEqual(automaticMask.data, Buffer.from([0x7f, 0x00, 0xcc, 0x00, 0x00, 0x0a]), 'builds mask from present RGBW properties');

  const explicitMask = {};
  DPTLib.populateAPDU({red: 0xff, mask: 0x01}, explicitMask, 'DPT251.600');
  t.deepEqual(explicitMask.data, Buffer.from([0xff, 0x00, 0x00, 0x00, 0x00, 0x01]), 'uses explicit mask when provided');

  t.end();
});

